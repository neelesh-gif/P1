const path = require('path');
const crypto = require('crypto');
const dotenv = require('dotenv');

// Load environment variables from .env file if it exists
dotenv.config({ path: path.resolve(__dirname, '..', '.env') });

// Generate a random high-entropy admin key if not set
const adminKey = process.env.ADMIN_KEY && process.env.ADMIN_KEY.trim() !== ''
  ? process.env.ADMIN_KEY.trim()
  : crypto.randomBytes(8).toString('hex');

const config = {
  port: parseInt(process.env.PORT || '3000', 10),
  host: process.env.HOST || '0.0.0.0',
  adminKey,
  isAutoGeneratedAdminKey: !(process.env.ADMIN_KEY && process.env.ADMIN_KEY.trim() !== ''),
  dbMode: process.env.DB_MODE || ':memory:',
  autoWipeOnShutdown: process.env.AUTO_WIPE_ON_SHUTDOWN !== 'false',
  maxFileSizeMb: parseInt(process.env.MAX_FILE_SIZE_MB || '10', 10),
  defaultTokenExpiryMinutes: parseInt(process.env.DEFAULT_TOKEN_EXPIRY_MINUTES || '60', 10),
  paths: {
    root: path.resolve(__dirname, '..'),
    public: path.resolve(__dirname, '..', 'public'),
    uploads: path.resolve(__dirname, '..', 'uploads'),
    data: path.resolve(__dirname, '..', 'data'),
  }
};

module.exports = config;
